/// Devuelve las 7 filas de 5 bits del caracter, si la fuente lo tiene.
pub fn glifo(c: char) -> Option<[u8; 7]> {
    // La mayuscula es la misma letra: se prueba tal cual y, si no hay, con la
    // version en mayusculas (las minusculas se guardan aparte, pero algunas
    // etiquetas usan mayusculas small-caps).
    if let Some((_, bits)) = GLIFOS.iter().find(|(ch, _)| *ch == c) {
        return Some(*bits);
    }
    let upper: Vec<char> = c.to_uppercase().collect();
    if upper.len() == 1 {
        if let Some((_, bits)) = GLIFOS.iter().find(|(ch, _)| *ch == upper[0]) {
            return Some(*bits);
        }
    }
    None
}
